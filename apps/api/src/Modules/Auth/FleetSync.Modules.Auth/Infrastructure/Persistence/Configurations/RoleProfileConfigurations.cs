using FleetSync.Modules.Auth.Domain;
using FleetSync.Modules.Auth.Domain.Roles;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace FleetSync.Modules.Auth.Infrastructure.Persistence.Configurations;

// EER role subtypes: user_id is both the primary key and the foreign key to
// USER, so a user can have at most one row per table. Deleting the account
// deletes its subtype row.

internal sealed class FleetAdministratorConfiguration : IEntityTypeConfiguration<FleetAdministrator>
{
    public void Configure(EntityTypeBuilder<FleetAdministrator> builder) =>
        RoleProfileMapping.Map(builder, "FleetAdministrators", a => a.UserId);
}

internal sealed class FleetOwnerConfiguration : IEntityTypeConfiguration<FleetOwner>
{
    public void Configure(EntityTypeBuilder<FleetOwner> builder) =>
        RoleProfileMapping.Map(builder, "FleetOwners", o => o.UserId);
}

internal sealed class OperationalCoordinatorConfiguration : IEntityTypeConfiguration<OperationalCoordinator>
{
    public void Configure(EntityTypeBuilder<OperationalCoordinator> builder) =>
        RoleProfileMapping.Map(builder, "OperationalCoordinators", c => c.UserId);
}

internal sealed class MechanicConfiguration : IEntityTypeConfiguration<Mechanic>
{
    public void Configure(EntityTypeBuilder<Mechanic> builder) =>
        RoleProfileMapping.Map(builder, "Mechanics", m => m.UserId);
}

internal sealed class DriverConfiguration : IEntityTypeConfiguration<Driver>
{
    public void Configure(EntityTypeBuilder<Driver> builder)
    {
        RoleProfileMapping.Map(builder, "Drivers", d => d.UserId);

        // licence_number VARCHAR(30) UNIQUE.
        builder.Property(d => d.LicenceNumber).HasMaxLength(30).IsRequired();
        builder.HasIndex(d => d.LicenceNumber).IsUnique();

        builder.Property(d => d.LicenceClass).HasConversion<string>().HasMaxLength(20);
    }
}

internal sealed class CustomerConfiguration : IEntityTypeConfiguration<Customer>
{
    public void Configure(EntityTypeBuilder<Customer> builder)
    {
        RoleProfileMapping.Map(builder, "Customers", c => c.UserId);

        builder.HasIndex(c => c.CompanyId);

        // company_id → CUSTOMER_COMPANY, nullable. Deleting a company keeps its contacts.
        builder.HasOne<CustomerCompany>().WithMany().HasForeignKey(c => c.CompanyId).OnDelete(DeleteBehavior.SetNull);
    }
}

internal sealed class CustomerCompanyConfiguration : IEntityTypeConfiguration<CustomerCompany>
{
    public void Configure(EntityTypeBuilder<CustomerCompany> builder)
    {
        builder.ToTable("CustomerCompanies");
        builder.HasKey(c => c.Id);

        builder.Property(c => c.CompanyName).HasMaxLength(200).IsRequired();
        builder.Property(c => c.BusinessRegistrationNo).HasMaxLength(50).IsRequired();
        builder.Property(c => c.NormalizedBusinessRegistrationNo).HasMaxLength(50).IsRequired();
        builder.Property(c => c.BillingAddress).HasMaxLength(500).IsRequired();

        // One company per registration number; new contacts join the existing row.
        builder.HasIndex(c => c.NormalizedBusinessRegistrationNo).IsUnique();
    }
}

/// <summary>Shared mapping for the role subtype tables.</summary>
internal static class RoleProfileMapping
{
    public static void Map<T>(
        EntityTypeBuilder<T> builder,
        string table,
        System.Linq.Expressions.Expression<Func<T, object?>> userId)
        where T : class
    {
        builder.ToTable(table);
        builder.HasKey(userId);

        // The key is the user's id, never generated by the database.
        builder.Property(userId).ValueGeneratedNever();

        builder.HasOne<ApplicationUser>().WithOne().HasForeignKey<T>(userId).OnDelete(DeleteBehavior.Cascade);
    }
}
