import { useState } from 'react'
import { AuthLayout } from '@/components/layout/AuthLayout'
import { RegistrationSubmitted } from '../components/RegistrationSubmitted'
import { StaffApplicationForm } from '../components/StaffApplicationForm'
import type {
  RegistrationSubmission,
  StaffApplicationFormInfo,
  StaffApplicationRequest,
} from '../types/auth'
import { getFirstName } from '../utils/registration'
import { staffRoleLabels } from '../utils/staffRoles'

/**
 * `/request-staff-account` route: drivers, mechanics and coordinators apply for
 * an account, which a Fleet Administrator later approves or rejects.
 * Owns the data loading and submission logic. After a successful submit the
 * form is replaced by the confirmation screen.
 */
export function StaffApplicationPage() {
  // TODO: the design shows a form generated by the Fleet Administrator
  // (e.g. "APP-2026-0124", with an expiry date). Once the backend exists, read the
  // form token from the link (e.g. ?form=...) and load its details here; until
  // then no form is known, so the info banner is hidden.
  const applicationForm: StaffApplicationFormInfo | undefined = undefined

  // Set once the application is submitted; switches the page to the confirmation view.
  const [submission, setSubmission] = useState<RegistrationSubmission>()

  function handleSubmit(values: StaffApplicationRequest) {
    // TODO: send to the application API as multipart/form-data (documents are files), and:
    //  - pass isSubmitting to the form while the request runs
    //  - show server errors (e.g. form expired, email already used) with the danger Banner
    //  - only continue below on success, filling `reference` from the response
    setSubmission({
      reference: undefined,
      firstName: getFirstName(values.fullName),
      email: values.email,
      accountType: `Staff · ${staffRoleLabels[values.role]}`,
      submittedAt: new Date(),
    })
  }

  function handleResendVerification() {
    // TODO: call the "resend verification email" API once it exists.
  }

  return (
    <AuthLayout>
      {submission ? (
        <RegistrationSubmitted
          submission={submission}
          onResendVerification={handleResendVerification}
        />
      ) : (
        <StaffApplicationForm onSubmit={handleSubmit} applicationForm={applicationForm} />
      )}
    </AuthLayout>
  )
}
