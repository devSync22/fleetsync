import { useState } from 'react'
import { RegistrationSubmitted } from '../components/RegistrationSubmitted'
import { StaffApplicationForm } from '../components/StaffApplicationForm'
import { useSubmit } from '../hooks/useSubmit'
import { submitStaffApplication } from '../services/authApi'
import type { RegistrationSubmission, StaffApplicationFormInfo, StaffApplicationRequest } from '../types'
import { getFirstName } from '../utils/names'
import { staffRoleLabels } from '../utils/staffRoles'

/**
 * `/auth/request-staff-account`: drivers, mechanics and coordinators apply for
 * an account, which a Fleet Administrator approves or rejects.
 */
export function StaffApplicationPage() {
  // TODO: the design shows a form generated by the Fleet Administrator
  // (e.g. "APP-2026-0124", with an expiry date). The API has no endpoint for
  // admin-generated forms yet; until it does, no form is known and the info
  // banner stays hidden.
  const applicationForm: StaffApplicationFormInfo | undefined = undefined

  // Set once the application is accepted; switches the page to the confirmation view.
  const [submission, setSubmission] = useState<RegistrationSubmission>()
  const { submit, isSubmitting, error } = useSubmit(submitStaffApplication)

  async function handleSubmit(values: StaffApplicationRequest) {
    const result = await submit(values)
    if (result) {
      setSubmission({
        kind: 'staff',
        reference: result.reference,
        firstName: getFirstName(values.fullName),
        email: result.email,
        accountType: `Staff · ${staffRoleLabels[values.role]}`,
        submittedAt: new Date(result.submittedAt),
      })
    }
  }

  if (submission) {
    return <RegistrationSubmitted submission={submission} />
  }

  return (
    <StaffApplicationForm
      onSubmit={handleSubmit}
      isSubmitting={isSubmitting}
      applicationForm={applicationForm}
      error={error}
    />
  )
}
